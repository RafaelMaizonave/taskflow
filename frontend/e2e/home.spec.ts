import { expect, test } from '@playwright/test'

test('protege o dashboard e exibe login sem erros', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/tarefas')
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole('heading', { name: 'Bom ter você de volta' })).toBeVisible()
  await expect(page.getByLabel('E-mail', { exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('login.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('cadastro, login, tarefas, filtros e logout com API real', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const email = `browser-${crypto.randomUUID()}@example.com`
  const password = 'Senha-segura-123'
  await page.goto('/cadastro')
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByLabel('Confirmar senha').fill('Outra-senha-123')
  await page.getByRole('button', { name: 'Criar conta' }).click()
  await expect(page.getByRole('alert')).toHaveText('As senhas não coincidem.')
  await page.getByLabel('Confirmar senha').fill(password)
  await page.getByRole('button', { name: 'Criar conta' }).click()
  await expect(page.getByRole('status')).toContainText('Conta criada')
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill('Senha-incorreta-123')
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('alert')).toContainText('Credenciais inválidas')
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('heading', { name: 'Minhas tarefas.' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Nenhuma tarefa por aqui' })).toBeVisible()
  await page.getByRole('button', { name: 'Nova tarefa', exact: false }).click()
  await page.getByLabel('Título', { exact: true }).fill('Revisar a entrega')
  await page.getByLabel('Descrição', { exact: false }).fill('Teste completo no navegador')
  await page.getByRole('button', { name: 'Salvar tarefa' }).click()
  await expect(page.getByRole('heading', { name: 'Revisar a entrega', exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('dashboard.png'), fullPage: true })
  await page.getByRole('button', { name: 'Editar Revisar a entrega' }).click()
  await page.getByLabel('Título', { exact: true }).fill('Entrega revisada')
  await page.getByRole('button', { name: 'Salvar tarefa' }).click()
  await expect(page.getByRole('heading', { name: 'Entrega revisada', exact: true })).toBeVisible()
  await page.getByLabel('Status de Entrega revisada', { exact: true }).selectOption('completed')
  await expect(page.getByRole('status')).toHaveText('Status atualizado.')
  await page.getByLabel('Filtrar por status').selectOption('pending')
  await page.getByRole('button', { name: 'Aplicar filtros' }).click()
  await expect(page.getByRole('heading', { name: 'Nenhuma tarefa por aqui' })).toBeVisible()
  await page.getByLabel('Filtrar por status').selectOption('completed')
  await page.getByLabel('Pesquisar por título').fill('revisada')
  await page.getByRole('button', { name: 'Aplicar filtros' }).click()
  await expect(page.getByRole('heading', { name: 'Entrega revisada', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: 'Excluir Entrega revisada' }).click()
  await expect(page.getByRole('heading', { name: 'Entrega revisada', exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Excluir Entrega revisada' }).click()
  await expect(page.getByRole('heading', { name: 'Nenhuma tarefa por aqui' })).toBeVisible()
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])
  await page.reload()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('heading', { name: 'Minhas tarefas.' })).toBeVisible()
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goto('/tarefas')
  await expect(page).toHaveURL(/\/login$/)
  expect(errors).toEqual([])
})

test('encerra a sessão quando uma requisição autenticada recebe 401', async ({ page }) => {
  const credentials = { email: `expired-${crypto.randomUUID()}@example.com`, password: 'Senha-segura-123' }
  await page.request.post('/api/v1/auth/register', { data: credentials })
  await page.goto('/login')
  await page.getByLabel('E-mail', { exact: true }).fill(credentials.email)
  await page.getByLabel('Senha', { exact: true }).fill(credentials.password)
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('heading', { name: 'Minhas tarefas.' })).toBeVisible()
  await page.route('**/api/v1/tasks*', route => route.fulfill({ status: 401, contentType: 'application/json', body: '{"detail":"Token inválido ou expirado"}' }))
  await page.getByRole('button', { name: 'Aplicar filtros' }).click()
  await expect(page).toHaveURL(/\/login\?expired=1$/)
  await expect(page.getByRole('status')).toContainText('Sua sessão expirou')
})
